"""Write requirements-api.txt with the exact versions installed in the current environment.

Run from the project root, inside the virtual environment you trained the model in:
    python scripts/pin_api_requirements.py

Why: a saved scikit-learn model must be loaded with the same scikit-learn version it was
trained with. Pinning the Docker image to your environment guarantees that.
"""
from importlib.metadata import version
from pathlib import Path

PACKAGES = [
    "pandas", "numpy", "scipy", "scikit-learn", "joblib",
    "fastapi", "starlette", "uvicorn", "pydantic", "prometheus-client",
]
OUT_FILE = Path(__file__).resolve().parents[1] / "requirements-api.txt"
HEADER = (
    "# Runtime dependencies for the Docker image, pinned to the versions the model was trained with.\n"
    "# Generated by scripts/pin_api_requirements.py - regenerate after retraining in a new environment.\n"
)


def build_requirements(packages=PACKAGES) -> str:
    return HEADER + "".join(f"{name}=={version(name)}\n" for name in packages)


if __name__ == "__main__":
    OUT_FILE.write_text(build_requirements())
    print(f"Wrote {OUT_FILE}")
    print(OUT_FILE.read_text())
